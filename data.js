// Helper function to get ancient text information
function getAncientTextInfo(textKey) {
    const texts = STAR_HORARY_LITERATURE.classical_texts;
    const found = texts.find(t => t.title.toLowerCase().includes(textKey.toLowerCase()));
    return found || null;
}

// Helper function to get symbolic star info
function getSymbolicStar(starName) {
    return STAR_HORARY_LITERATURE.shen_sha[starName] || null;
}

// Helper function to calculate all symbolic stars for a BaZi chart
function calculateSymbolicStars(dayStem, yearBranch) {
    const h = STAR_HORARY_LITERATURE.helpers;
    return {
        noblePerson: h.getNoblePerson(dayStem),
        academicStar: h.getAcademicStar(dayStem),
        peachBlossom: h.getPeachBlossom(
            EARTHLY_BRANCHES.find(b => b.name.toLowerCase() === yearBranch.toLowerCase())?.zodiac
        )
    };
}


